"""Counted Adam VQE baseline for the sparse non-Clifford parent-Hamiltonian benchmark.

Uses the same make_problem() and EnergyOracle as llm.py. Every parameter-shift
or finite-difference energy call is billed, including the initial evaluation
and one post-update evaluation per Adam step. Exact ideal energies recorded for
analysis are unbilled diagnostics, not optimization feedback.
"""
import argparse
import json
from pathlib import Path

import numpy as np

from circuit import canonical_angles, initial_parameters, parameter_names
from hamiltonian import EnergyOracle, descriptions, make_problem


def gradient(oracle, theta, method='parameter-shift', fd_step=0.01):
    """Compute a two-query-per-parameter gradient using the energy oracle.

    Parameter shift is exact in the noiseless expectation for independently
    parameterized RX, RY, and RZ gates (each generated by P/2). Under finite
    sampling it estimates the gradient; a parameter-independent noise model
    retains the shift identity in expectation.
    """
    if method not in ('parameter-shift', 'finite-difference'):
        raise ValueError(f'Unsupported gradient method: {method}')
    if fd_step <= 0:
        raise ValueError('fd_step must be positive')
    theta = np.asarray(theta, dtype=float)
    step = np.pi / 2 if method == 'parameter-shift' else fd_step
    denominator = 2.0 if method == 'parameter-shift' else 2.0 * fd_step
    grad = np.empty_like(theta)
    for index in range(theta.size):
        delta = np.zeros_like(theta)
        delta[index] = step
        e_plus = oracle.energy(theta + delta)
        e_minus = oracle.energy(theta - delta)
        grad[index] = (e_plus - e_minus) / denominator
    return grad


def run(n=4, layers=2, active_per_layer=None, k=8, seed=42, max_depth=100,
        max_attempts=250, steps=40, lr=0.08, gradient_method='parameter-shift',
        fd_step=0.01, shots=0, noise=False, init_seed=123, init_scale=0.3,
        shot_seed=2026, output=None, non_clifford_count=1):
    """Optimize an identical parent instance to the LLM, given matching flags."""
    if steps < 0:
        raise ValueError('steps must be >= 0')
    if not np.isfinite(lr) or lr <= 0:
        raise ValueError('lr must be positive and finite')
    if gradient_method not in ('parameter-shift', 'finite-difference'):
        raise ValueError('gradient must be parameter-shift or finite-difference')
    if fd_step <= 0:
        raise ValueError('fd_step must be positive')

    problem = make_problem(
        n, layers, active_per_layer, k, seed, max_depth, max_attempts,
        non_clifford_count=non_clifford_count,
    )
    oracle = EnergyOracle(problem, shots, noise, shot_seed)
    theta = initial_parameters(problem.gates, init_seed, init_scale)
    count = len(parameter_names(problem.gates))
    if theta.size != count:
        raise RuntimeError('Initial-parameter dimension disagrees with the ansatz')

    moment1 = np.zeros_like(theta)
    moment2 = np.zeros_like(theta)
    trace = []
    filename = output or (
        f'results/adam_{problem.instance_id}_'
        f'{"noisy" if noise else "ideal"}_k{shots}.json'
    )

    def save():
        result = {
            'method': f'adam_{gradient_method.replace("-", "_")}',
            'problem': 'parent_hamiltonian',
            'instance_id': problem.instance_id,
            'config': {
                'n': n, 'layers': layers, 'active_per_layer': active_per_layer,
                'k': k, 'seed': seed, 'max_depth': max_depth,
                'max_attempts': max_attempts,
                'non_clifford_count': non_clifford_count,
                'steps': steps, 'lr': lr, 'gradient': gradient_method,
                'fd_step': fd_step if gradient_method == 'finite-difference' else None,
                'shots_per_energy_query': shots, 'noise': noise,
                'init_seed': init_seed, 'init_scale': init_scale,
                'shot_seed': shot_seed,
            },
            'hamiltonian': descriptions(problem.terms),
            'pauli_count': len(problem.terms),
            'parameter_count': count,
            'native_depth': problem.native_depth,
            'ground_energy': 0.0,
            'trace': trace,
            'private': {
                'hidden_theta': problem.hidden_theta.tolist(),
                'topology_seed': problem.topology_seed,
                'generation_attempts': problem.attempts,
                'non_clifford_indices': list(problem.non_clifford_indices),
            },
        }
        path = Path(filename)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(result, indent=2), encoding='utf-8')
        return result

    def record(step, measured):
        # Diagnostic only; this ideal reference is never used by Adam's update.
        ideal = oracle.ideal_unbilled(theta)
        trace.append({
            'step': step,
            'evaluations': oracle.evaluations,
            'shots': oracle.total_shots,
            'estimated_energy': float(measured),
            'exact_energy': float(ideal),
            'exact_gap': max(0.0, float(ideal)),
            'theta': theta.tolist(),
        })
        print(
            f'Adam step={step}/{steps} observed={measured:.9g} '
            f'ideal={ideal:.9g} evals={oracle.evaluations} '
            f'shots={oracle.total_shots}', flush=True,
        )

    print(
        f'Instance {problem.instance_id}: n={n}, layers={layers}, '
        f'parameters={count}, Pauli terms={len(problem.terms)}, '
        f'non-Clifford hidden rotations={non_clifford_count}', flush=True,
    )
    record(0, oracle.energy(theta))
    save()
    for step in range(1, steps + 1):
        grad = gradient(oracle, theta, gradient_method, fd_step)
        moment1 = 0.9 * moment1 + 0.1 * grad
        moment2 = 0.999 * moment2 + 0.001 * (grad * grad)
        m_hat = moment1 / (1 - 0.9 ** step)
        v_hat = moment2 / (1 - 0.999 ** step)
        theta = canonical_angles(
            theta - lr * m_hat / (np.sqrt(v_hat) + 1e-8),
            problem.gates,
        )
        record(step, oracle.energy(theta))
        save()
    print(f'Saved {filename}', flush=True)
    return save()


def cli():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument('--n', type=int, default=4)
    parser.add_argument('--layers', type=int, default=2)
    parser.add_argument('--active-per-layer', type=int, default=None, help='Legacy compatibility: omit or set equal to n')
    parser.add_argument('--k', type=int, default=6)
    parser.add_argument('--non-clifford-count', type=int, default=1, help='Non-Clifford angles in the hidden parent-state generator')
    parser.add_argument('--seed', type=int, default=42)
    parser.add_argument('--max-depth', type=int, default=100)
    parser.add_argument('--max-attempts', type=int, default=250)
    parser.add_argument('--steps', type=int, default=10)
    parser.add_argument('--lr', type=float, default=0.1)
    parser.add_argument('--gradient', dest='gradient_method', choices=('parameter-shift', 'finite-difference'), default='parameter-shift')
    parser.add_argument('--fd-step', type=float, default=0.01)
    parser.add_argument('--shots', type=int, default=200)
    parser.add_argument('--noise', action=argparse.BooleanOptionalAction, default=False)
    parser.add_argument('--init-seed', type=int, default=123)
    parser.add_argument('--init-scale', type=float, default=0.3)
    parser.add_argument('--shot-seed', type=int, default=2026)
    parser.add_argument('--output', default=None)
    return run(**vars(parser.parse_args()))


if __name__ == '__main__':
    cli()
